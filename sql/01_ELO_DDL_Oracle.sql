CREATE TABLE TB_NUCLEO_CUIDADO (
    ID_NUCLEO       NUMBER(6)     NOT NULL,
    NOME_NUCLEO     VARCHAR2(100) NOT NULL,
    DESCRICAO       VARCHAR2(300),
    CIDADE          VARCHAR2(60)  NOT NULL,
    UF              CHAR(2)       NOT NULL,
    DT_CRIACAO      DATE          DEFAULT SYSDATE NOT NULL,
    CONSTRAINT PK_NUCLEO PRIMARY KEY (ID_NUCLEO)
);

CREATE TABLE TB_USUARIO (
    ID_USUARIO       NUMBER(6)      NOT NULL,
    NOME_COMPLETO    VARCHAR2(120)  NOT NULL,
    EMAIL            VARCHAR2(120)  NOT NULL,
    TELEFONE         VARCHAR2(20),
    PERFIL_PRINCIPAL VARCHAR2(30)   NOT NULL,
    RECEBE_WHATSAPP  CHAR(1)        DEFAULT 'N' NOT NULL,
    CIDADE           VARCHAR2(60),
    UF               CHAR(2),
    CONSTRAINT PK_USUARIO PRIMARY KEY (ID_USUARIO),
    CONSTRAINT UK_USUARIO_EMAIL UNIQUE (EMAIL),
    CONSTRAINT CK_USUARIO_WHATS CHECK (RECEBE_WHATSAPP IN ('S', 'N')),
    CONSTRAINT CK_USUARIO_PERFIL CHECK (PERFIL_PRINCIPAL IN ('CUIDADOR', 'FAMILIAR'))
);

CREATE TABLE TB_PARTICIPANTE_NUCLEO (
    ID_PARTICIPANTE              NUMBER(6)     NOT NULL,
    ID_NUCLEO                    NUMBER(6)     NOT NULL,
    ID_USUARIO                   NUMBER(6)     NOT NULL,
    PAPEL                        VARCHAR2(30)  NOT NULL,
    DISPONIBILIDADE_HORAS_SEMANA NUMBER(5,2)   NOT NULL,
    CARGA_ATUAL_HORAS            NUMBER(5,2)   NOT NULL,
    ATIVO                        CHAR(1)       DEFAULT 'S' NOT NULL,
    CONSTRAINT PK_PART PRIMARY KEY (ID_PARTICIPANTE),
    CONSTRAINT UK_PART_NUCLEO_USUARIO UNIQUE (ID_NUCLEO, ID_USUARIO),
    CONSTRAINT UK_PART_NUCLEO_ID UNIQUE (ID_PARTICIPANTE, ID_NUCLEO),
    CONSTRAINT CK_PART_ATIVO CHECK (ATIVO IN ('S', 'N')),
    CONSTRAINT CK_PART_PAPEL CHECK (PAPEL IN ('CUIDADOR_PRINCIPAL', 'FAMILIAR_COLABORADOR')),
    CONSTRAINT CK_PART_HORAS CHECK (DISPONIBILIDADE_HORAS_SEMANA >= 0 AND CARGA_ATUAL_HORAS >= 0)
);

CREATE TABLE TB_PESSOA_CUIDADA (
    ID_PESSOA_CUIDADA NUMBER(6)      NOT NULL,
    ID_NUCLEO         NUMBER(6)      NOT NULL,
    NOME_COMPLETO     VARCHAR2(120)  NOT NULL,
    DATA_NASCIMENTO   DATE           NOT NULL,
    GRAU_DEPENDENCIA  VARCHAR2(10)   NOT NULL,
    OBSERVACOES       VARCHAR2(300),
    CONTATO_EMERGENCIA VARCHAR2(100),
    CONSTRAINT PK_PESSOA PRIMARY KEY (ID_PESSOA_CUIDADA),
    CONSTRAINT UK_PESSOA_NUCLEO UNIQUE (ID_PESSOA_CUIDADA, ID_NUCLEO),
    CONSTRAINT CK_PESSOA_GRAU CHECK (GRAU_DEPENDENCIA IN ('BAIXA', 'MEDIA', 'ALTA'))
);

CREATE TABLE TB_TAREFA_CUIDADO (
    ID_TAREFA          NUMBER(6)      NOT NULL,
    ID_NUCLEO          NUMBER(6)      NOT NULL,
    ID_PESSOA_CUIDADA  NUMBER(6)      NOT NULL,
    TITULO             VARCHAR2(120)  NOT NULL,
    CATEGORIA          VARCHAR2(40)   NOT NULL,
    FREQUENCIA         VARCHAR2(30)   NOT NULL,
    TEMPO_ESTIMADO_MIN NUMBER(5)      NOT NULL,
    PRIORIDADE         VARCHAR2(10)   NOT NULL,
    CONSTRAINT PK_TAREFA PRIMARY KEY (ID_TAREFA),
    CONSTRAINT UK_TAREFA_NUCLEO UNIQUE (ID_TAREFA, ID_NUCLEO),
    CONSTRAINT CK_TAREFA_TEMPO CHECK (TEMPO_ESTIMADO_MIN > 0),
    CONSTRAINT CK_TAREFA_PRIOR CHECK (PRIORIDADE IN ('BAIXA', 'MEDIA', 'ALTA'))
);

CREATE TABLE TB_ATRIBUICAO_TAREFA (
    ID_ATRIBUICAO    NUMBER(6)     NOT NULL,
    ID_NUCLEO        NUMBER(6)     NOT NULL,
    ID_TAREFA        NUMBER(6)     NOT NULL,
    ID_PARTICIPANTE  NUMBER(6)     NOT NULL,
    DATA_PREVISTA    DATE          NOT NULL,
    STATUS           VARCHAR2(20)  NOT NULL,
    DATA_CONCLUSAO   DATE,
    OBSERVACAO       VARCHAR2(300),
    CONSTRAINT PK_ATRIB PRIMARY KEY (ID_ATRIBUICAO),
    CONSTRAINT CK_ATRIB_STATUS CHECK (STATUS IN ('PENDENTE', 'EM_ANDAMENTO', 'CONCLUIDA')),
    CONSTRAINT CK_ATRIB_CONCLUSAO CHECK (DATA_CONCLUSAO IS NULL OR DATA_CONCLUSAO >= DATA_PREVISTA - 1)
);

CREATE TABLE TB_EVENTO_AGENDA (
    ID_EVENTO           NUMBER(6)     NOT NULL,
    ID_NUCLEO           NUMBER(6)     NOT NULL,
    ID_PESSOA_CUIDADA   NUMBER(6)     NOT NULL,
    ID_PARTICIPANTE_RESP NUMBER(6),
    TITULO              VARCHAR2(120) NOT NULL,
    TIPO_EVENTO         VARCHAR2(30)  NOT NULL,
    DATA_EVENTO         DATE          NOT NULL,
    LOCAL_EVENTO        VARCHAR2(120),
    STATUS_EVENTO       VARCHAR2(20)  NOT NULL,
    CONSTRAINT PK_EVENTO PRIMARY KEY (ID_EVENTO),
    CONSTRAINT CK_EVENTO_TIPO CHECK (TIPO_EVENTO IN ('CONSULTA', 'EXAME', 'MEDICAMENTO', 'TERAPIA', 'COMPROMISSO')),
    CONSTRAINT CK_EVENTO_STATUS CHECK (STATUS_EVENTO IN ('AGENDADO', 'REALIZADO', 'CANCELADO'))
);

CREATE TABLE TB_CHECKIN_SOBRECARGA (
    ID_CHECKIN            NUMBER(6)     NOT NULL,
    ID_PARTICIPANTE       NUMBER(6)     NOT NULL,
    DATA_CHECKIN          DATE          NOT NULL,
    NIVEL_SOBRECARGA      NUMBER(1)     NOT NULL,
    HORAS_CUIDADO_SEMANA  NUMBER(5,2)   NOT NULL,
    PRECISOU_AJUDA        CHAR(1)       NOT NULL,
    COMENTARIO            VARCHAR2(300),
    CONSTRAINT PK_CHECKIN PRIMARY KEY (ID_CHECKIN),
    CONSTRAINT CK_CHECKIN_NIVEL CHECK (NIVEL_SOBRECARGA BETWEEN 1 AND 5),
    CONSTRAINT CK_CHECKIN_HORAS CHECK (HORAS_CUIDADO_SEMANA >= 0),
    CONSTRAINT CK_CHECKIN_AJUDA CHECK (PRECISOU_AJUDA IN ('S', 'N'))
);

CREATE TABLE TB_REDE_APOIO (
    ID_APOIO         NUMBER(6)     NOT NULL,
    NOME_INSTITUICAO VARCHAR2(120) NOT NULL,
    TIPO_INSTITUICAO VARCHAR2(40)  NOT NULL,
    CIDADE           VARCHAR2(60)  NOT NULL,
    UF               CHAR(2)       NOT NULL,
    TELEFONE         VARCHAR2(20),
    PUBLICO_ATENDIDO VARCHAR2(100),
    DESCRICAO        VARCHAR2(300),
    CONSTRAINT PK_APOIO PRIMARY KEY (ID_APOIO)
);

CREATE TABLE TB_ENCAMINHAMENTO_APOIO (
    ID_ENCAMINHAMENTO NUMBER(6)     NOT NULL,
    ID_NUCLEO         NUMBER(6)     NOT NULL,
    ID_APOIO          NUMBER(6)     NOT NULL,
    DT_ENCAMINHAMENTO DATE          NOT NULL,
    STATUS            VARCHAR2(20)  NOT NULL,
    OBSERVACAO        VARCHAR2(300),
    CONSTRAINT PK_ENCAMINHAMENTO PRIMARY KEY (ID_ENCAMINHAMENTO),
    CONSTRAINT UK_ENCAM_NUCLEO_APOIO UNIQUE (ID_NUCLEO, ID_APOIO),
    CONSTRAINT CK_ENCAM_STATUS CHECK (STATUS IN ('SUGERIDO', 'CONTATADO', 'ATENDIDO'))
);

/* FOREIGN KEYS - definidas via ALTER TABLE, como estudado em aula */
ALTER TABLE TB_PARTICIPANTE_NUCLEO ADD CONSTRAINT FK_PART_NUCLEO
  FOREIGN KEY (ID_NUCLEO) REFERENCES TB_NUCLEO_CUIDADO (ID_NUCLEO);
ALTER TABLE TB_PARTICIPANTE_NUCLEO ADD CONSTRAINT FK_PART_USUARIO
  FOREIGN KEY (ID_USUARIO) REFERENCES TB_USUARIO (ID_USUARIO);
ALTER TABLE TB_PESSOA_CUIDADA ADD CONSTRAINT FK_PESSOA_NUCLEO
  FOREIGN KEY (ID_NUCLEO) REFERENCES TB_NUCLEO_CUIDADO (ID_NUCLEO);
ALTER TABLE TB_TAREFA_CUIDADO ADD CONSTRAINT FK_TAREFA_PESSOA_NUCLEO
  FOREIGN KEY (ID_PESSOA_CUIDADA, ID_NUCLEO)
  REFERENCES TB_PESSOA_CUIDADA (ID_PESSOA_CUIDADA, ID_NUCLEO);
ALTER TABLE TB_ATRIBUICAO_TAREFA ADD CONSTRAINT FK_ATRIB_TAREFA_NUCLEO
  FOREIGN KEY (ID_TAREFA, ID_NUCLEO)
  REFERENCES TB_TAREFA_CUIDADO (ID_TAREFA, ID_NUCLEO);
ALTER TABLE TB_ATRIBUICAO_TAREFA ADD CONSTRAINT FK_ATRIB_PART_NUCLEO
  FOREIGN KEY (ID_PARTICIPANTE, ID_NUCLEO)
  REFERENCES TB_PARTICIPANTE_NUCLEO (ID_PARTICIPANTE, ID_NUCLEO);
ALTER TABLE TB_EVENTO_AGENDA ADD CONSTRAINT FK_EVENTO_PESSOA_NUCLEO
  FOREIGN KEY (ID_PESSOA_CUIDADA, ID_NUCLEO)
  REFERENCES TB_PESSOA_CUIDADA (ID_PESSOA_CUIDADA, ID_NUCLEO);
ALTER TABLE TB_EVENTO_AGENDA ADD CONSTRAINT FK_EVENTO_PART_NUCLEO
  FOREIGN KEY (ID_PARTICIPANTE_RESP, ID_NUCLEO)
  REFERENCES TB_PARTICIPANTE_NUCLEO (ID_PARTICIPANTE, ID_NUCLEO);
ALTER TABLE TB_CHECKIN_SOBRECARGA ADD CONSTRAINT FK_CHECKIN_PART
  FOREIGN KEY (ID_PARTICIPANTE) REFERENCES TB_PARTICIPANTE_NUCLEO (ID_PARTICIPANTE);
ALTER TABLE TB_ENCAMINHAMENTO_APOIO ADD CONSTRAINT FK_ENCAM_NUCLEO
  FOREIGN KEY (ID_NUCLEO) REFERENCES TB_NUCLEO_CUIDADO (ID_NUCLEO);
ALTER TABLE TB_ENCAMINHAMENTO_APOIO ADD CONSTRAINT FK_ENCAM_APOIO
  FOREIGN KEY (ID_APOIO) REFERENCES TB_REDE_APOIO (ID_APOIO);
